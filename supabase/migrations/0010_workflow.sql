create or replace function public.pending_validation_count()
returns int
language sql
stable
security definer
set search_path = ''
as $fn$
  select count(*)::int
  from public.obligation_occurrences oc
  where oc.status = 'PENDING_VALIDATION'
    and oc.deleted_at is null
    and public.can_see_occurrence(oc.id)
    and public.can_validate_occurrence(oc.id)
    and not public.self_validation_blocked(
          oc.obligation_type_id, oc.owner_id, public.current_profile_id());
$fn$;

comment on function public.pending_validation_count() is
  'Compteur affiché dans la navigation. Applique EXACTEMENT les mêmes conditions '
  'que la file elle-même, séparation des pouvoirs comprise : un compteur qui '
  'annonce trois dossiers pour une file qui en montre deux détruit la confiance '
  'dans les deux.';

