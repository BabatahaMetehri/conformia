-- =============================================================================
-- 6. LE TRIGGER APPLIQUE AUSSI LA RÈGLE DES DEUX NIVEAUX
-- =============================================================================

create or replace function public.validate_status_transition()
returns trigger
language plpgsql
security definer
set search_path = ''
as $fn$
declare
  rule public.status_transition_rules%rowtype;
  resolved_reason text;
  occ_domain uuid;
begin
  if new.status is not distinct from old.status then
    return new;
  end if;

  select * into rule
    from public.status_transition_rules
   where from_status = old.status
     and to_status = new.status;

  if not found then
    raise exception 'Transition interdite : % → %.', old.status, new.status
      using errcode = '23514',
            hint = 'Les transitions autorisées sont des données : voir public.status_transition_rules.';
  end if;

  -- Contrôle d'habilitation. Ignoré hors session (auth.uid() NULL) : les jobs de
  -- src/server/jobs/ et les migrations n'ont pas d'utilisateur, et sont déjà
  -- contraints par ailleurs. Un appel authentifié, lui, est toujours vérifié.
  if auth.uid() is not null then
    occ_domain := public.obligation_domain_of_type(new.obligation_type_id);

    if rule.required_permission = 'occurrence.validate' then
      -- Passe par can_validate_occurrence : elle intègre le filet DIRECTION.
      if not public.can_validate_occurrence(new.id) then
        raise exception 'Permission % requise pour la transition % → %.',
          rule.required_permission, old.status, new.status
          using errcode = '42501';
      end if;
    elsif not public.has_permission_in_domain(rule.required_permission, occ_domain) then
      raise exception 'Permission % requise pour la transition % → %.',
        rule.required_permission, old.status, new.status
        using errcode = '42501';
    end if;

    -- ⚠️ DOUBLE NIVEAU. Vérifié ICI, dans le trigger, et pas seulement dans la
    -- fonction d'application : un détenteur de `occurrence.write` peut émettre un
    -- UPDATE direct sur la table, et la règle serait alors contournée par le seul
    -- fait de ne pas passer par la porte prévue.
    if new.status = 'VALIDATED' and public.validation_levels_required(new.id) > 1 then
      if public.validation_steps_obtained(new.id) = 0 then
        raise exception
          'Cette obligation exige deux validations : la première n''a pas été enregistrée.'
          using errcode = '23514';
      end if;
      if not public.is_direction(auth.uid()) then
        raise exception 'La seconde validation est réservée à la DIRECTION.'
          using errcode = '42501';
      end if;
    end if;
  end if;

  resolved_reason := coalesce(
    public.app_transition_reason(),
    case new.status
      when 'NOT_APPLICABLE' then new.na_reason
      when 'REJECTED' then new.rejection_reason
      else null
    end
  );

  if rule.requires_reason and (resolved_reason is null or btrim(resolved_reason) = '') then
    raise exception 'Motif obligatoire pour la transition % → %.', old.status, new.status
      using errcode = '23514',
            hint = 'Renseigner la colonne de motif, ou poser SET LOCAL conformia.transition_reason.';
  end if;

  if rule.locks_occurrence then
    new.is_locked := true;
    new.locked_at := now();
    new.locked_by := public.app_actor_id();
  end if;

  if old.status = 'ARCHIVED' and new.status = 'SUBMITTED' then
    new.is_locked := false;
    new.locked_at := null;
    new.locked_by := null;
  end if;

  return new;
end;
$fn$;

comment on function public.validate_status_transition() is
  'Autorise ou refuse un changement d''état : existence de la transition dans '
  'status_transition_rules, permission requise, motif obligatoire, et second '
  'niveau de validation lorsque l''obligation l''exige. AUCUNE transition et '
  'AUCUNE permission ne sont écrites en dur — toutes sont des données.';

-- =============================================================================
-- 7. LE JOURNAL DÉCLENCHE LES EFFETS
-- =============================================================================

create or replace function public.record_status_transition()
returns trigger
language plpgsql
security definer
set search_path = ''
as $fn$
declare
  previous_status public.occurrence_status;
  resolved_reason text;
begin
  if tg_op = 'INSERT' then
    previous_status := null;
  else
    if new.status is not distinct from old.status then
      return null;
    end if;
    previous_status := old.status;
  end if;

  resolved_reason := coalesce(
    public.app_transition_reason(),
    case new.status
      when 'NOT_APPLICABLE' then new.na_reason
      when 'REJECTED' then new.rejection_reason
      else null
    end
  );

  insert into public.occurrence_transitions
    (occurrence_id, from_status, to_status, actor_id, on_behalf_of_id, reason, metadata)
  values (
    new.id,
    previous_status,
    new.status,
    public.app_actor_id(),
    -- Action sous délégation : on conserve le délégant, sans effacer l'auteur réel.
    (
      select d.delegator_id
      from public.validation_delegations d
      where d.delegate_id = auth.uid()
        and d.revoked_at is null
        and current_date between d.starts_at and d.ends_at
      limit 1
    ),
    resolved_reason,
    jsonb_build_object('origin', case when tg_op = 'INSERT' then 'CREATION' else 'TRANSITION' end)
  );

  -- ⚠️ MÊME TRANSACTION que la transition et que son journal. Si la notification
  -- ne peut pas s'écrire, la transition entière est annulée. C'est délibéré :
  -- un validateur qui n'est jamais prévenu ne valide jamais, et le dossier
  -- expire sans que personne n'ait rien vu passer.
  if tg_op <> 'INSERT' then
    perform public.dispatch_transition_notifications(new, previous_status, new.status, resolved_reason);
  end if;

  return null;
end;
$fn$;

comment on function public.record_status_transition() is
  'Écrit le journal d''état PUIS déclenche les effets déclarés dans '
  'transition_notifications, dans la même transaction. En SECURITY DEFINER : la '
  'table n''accepte aucune écriture directe, pas même de service_role. Renseigne '
  'on_behalf_of_id quand l''auteur agit sous délégation active.';

-- =============================================================================
-- 8. APPLICATION D'UNE TRANSITION
-- =============================================================================

create or replace function public.apply_occurrence_transition(
  p_occurrence_id uuid,
  p_to_status public.occurrence_status,
  p_expected_version int,
  p_reason text default null,
  p_reference_number text default null,
  p_late_reason_code public.late_reason_code default null,
  p_late_reason text default null
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $fn$
declare
  occ public.obligation_occurrences%rowtype;
  verdict jsonb;
  reason_clean text := nullif(pg_catalog.btrim(coalesce(p_reason, '')), '');
  obtained int;
begin
  -- Verrou de ligne AVANT toute évaluation : deux validations concurrentes se
  -- sérialisent, et la seconde voit l'étape que la première vient d'inscrire.
  select * into occ
  from public.obligation_occurrences
  where id = p_occurrence_id
  for update;

  if occ.id is null then
    return jsonb_build_object('outcome', 'NOT_FOUND');
  end if;

  -- ⚠️ Verrouillage optimiste, AVANT l'évaluation : un conflit de version doit
  -- se dire tel quel, et non se déguiser en refus métier.
  if occ.version <> p_expected_version and occ.status <> p_to_status then
    return jsonb_build_object(
      'outcome', 'VERSION_CONFLICT', 'version', occ.version, 'status', occ.status);
  end if;

  -- ⚠️ AUCUNE règle n'est réévaluée ici : la décision appartient entièrement à
  -- evaluate_transition, que l'interface consulte aussi. Cette fonction
  -- TRANSPORTE, elle ne décide pas.
  verdict := public.evaluate_transition(
    p_occurrence_id, p_to_status, p_reason, p_reference_number, p_late_reason_code);

  if verdict ->> 'outcome' <> 'ALLOWED' then
    return verdict;
  end if;

  -- Première des deux validations : on inscrit l'étape, l'état ne bouge pas.
  if verdict ->> 'effect' = 'PARTIAL_VALIDATION' then
    obtained := public.record_validation_step(p_occurrence_id);
    return jsonb_build_object(
      'outcome', 'PARTIALLY_VALIDATED',
      'obtained', obtained,
      'required', (verdict ->> 'required')::int,
      'version', occ.version,
      'status', occ.status);
  end if;

  -- Motif transporté jusqu'au trigger, pour les transitions dont le motif n'a
  -- pas de colonne dédiée (réouverture d'archive, retour d'un dossier sans objet).
  perform pg_catalog.set_config('conformia.transition_reason', coalesce(reason_clean, ''), true);

  update public.obligation_occurrences
     set status = p_to_status,
         started_at = case
           when p_to_status = 'IN_PROGRESS' then coalesce(started_at, pg_catalog.now())
           else started_at end,
         submitted_for_validation_at = case
           when p_to_status = 'PENDING_VALIDATION' then pg_catalog.now()
           else submitted_for_validation_at end,
         validated_at = case
           when p_to_status = 'VALIDATED' then pg_catalog.now() else validated_at end,
         validated_by = case
           when p_to_status = 'VALIDATED' then public.app_actor_id() else validated_by end,
         submitted_at = case
           when p_to_status = 'SUBMITTED' then pg_catalog.now() else submitted_at end,
         submitted_by = case
           when p_to_status = 'SUBMITTED' then public.app_actor_id() else submitted_by end,
         reference_number = coalesce(
           nullif(pg_catalog.btrim(coalesce(p_reference_number, '')), ''), reference_number),
         late_reason_code = case
           when p_to_status = 'SUBMITTED' then coalesce(p_late_reason_code, late_reason_code)
           else late_reason_code end,
         late_reason = case
           when p_to_status = 'SUBMITTED'
             then coalesce(nullif(pg_catalog.btrim(coalesce(p_late_reason, '')), ''), late_reason)
           else late_reason end,
         rejection_reason = case
           when p_to_status = 'REJECTED' then reason_clean else rejection_reason end,
         na_reason = case
           when p_to_status = 'NOT_APPLICABLE' then reason_clean else na_reason end
   where id = p_occurrence_id
     and version = p_expected_version;

  if not found then
    return jsonb_build_object('outcome', 'VERSION_CONFLICT');
  end if;

  select * into occ from public.obligation_occurrences where id = p_occurrence_id;

  return jsonb_build_object(
    'outcome', 'APPLIED', 'version', occ.version, 'status', occ.status);
end;
$fn$;

comment on function public.apply_occurrence_transition is
  'TRANSPORT d''une transition, jamais sa décision : depuis 0010, toutes les '
  'règles sont dans `evaluate_transition`, qu''elle appelle. Elle n''ajoute que ce '
  'que PostgREST ne sait pas exprimer : verrou de ligne, version attendue, GUC de '
  'motif, colonnes annexes, et l''inscription d''une validation de premier niveau. '
  'SECURITY DEFINER car obligation_occurrences_update exige occurrence.write, que '
  'DIRECTION ne détient pas alors qu''elle détient occurrence.validate, '
  'occurrence.mark_na et occurrence.unlock : sans cela, ces trois actions seraient '
  'des boutons sans effet.';

