-- =============================================================================
-- 0010 — CIRCUIT DE VALIDATION
--
-- Cinq apports, et pas un de plus :
--
--   1. UNE SEULE FONCTION DÉCIDE. `evaluate_transition()` répond « cette
--      transition est-elle possible, et sinon pourquoi ». Elle est appelée par
--      `apply_occurrence_transition()` — donc par toute écriture — ET par le
--      service TypeScript qui grise les boutons. Il n'existe désormais aucune
--      règle de transition écrite deux fois : ni entre SQL et TypeScript, ni
--      entre l'interface et la base.
--
--   2. DOUBLE NIVEAU DE VALIDATION. Quand `obligation_types.validation_levels`
--      vaut 2, la première validation ne change PAS l'état : elle inscrit une
--      étape dans `occurrence_transitions`. Le dossier reste en attente jusqu'à
--      ce que la DIRECTION valide à son tour. La règle est portée par le
--      TRIGGER, pas seulement par la fonction d'application — sinon un UPDATE
--      direct par un détenteur de `occurrence.write` la contournerait.
--
--   3. IMMUABILITÉ D'UNE PÉRIODE ARCHIVÉE. Le verrou de 0001 protégeait la ligne
--      d'occurrence. Il ne protégeait NI les commentaires, NI la liste de
--      contrôle : on pouvait commenter et cocher un dossier archivé. Corrigé.
--
--   4. EFFETS DE BORD DÉCLARÉS EN TABLE. Qui est prévenu, à quelle transition,
--      avec ou sans motif : des lignes, pas des `if`. Ajouter une notification
--      ne demande aucun déploiement.
--
--   5. NOTIFICATIONS. La table manquait. Elle est écrite dans la MÊME
--      TRANSACTION que la transition : une transition sans sa notification n'est
--      pas un demi-succès, c'est un échec.
-- =============================================================================

-- =============================================================================
-- 1. IMMUABILITÉ D'UNE PÉRIODE ARCHIVÉE
-- =============================================================================

create or replace function public.enforce_parent_occurrence_lock()
returns trigger
language plpgsql
security definer
set search_path = ''
as $fn$
declare
  target_occurrence uuid;
  locked boolean;
begin
  target_occurrence := coalesce(
    (to_jsonb(new) ->> 'occurrence_id')::uuid,
    (to_jsonb(old) ->> 'occurrence_id')::uuid);

  if target_occurrence is null then
    return new;
  end if;

  select oc.is_locked into locked
  from public.obligation_occurrences oc
  where oc.id = target_occurrence;

  if coalesce(locked, false) then
    raise exception
      'Dossier archivé (id=%) : aucune modification de % acceptée.', target_occurrence, tg_table_name
      using errcode = '23514',
            hint = 'Rouvrir le dossier par la transition ARCHIVED → SUBMITTED (permission occurrence.unlock).';
  end if;

  return new;
end;
$fn$;

comment on function public.enforce_parent_occurrence_lock() is
  '⚠️ COMBLE UNE LACUNE de 0001. `enforce_occurrence_lock` protégeait la LIGNE '
  'd''occurrence — son statut, ses dates — mais rien de ce qui pend à elle. Un '
  'dossier archivé acceptait donc encore un commentaire et une coche de liste de '
  'contrôle : l''archive n''était pas fidèle à ce qui avait été déposé. '
  'Générique par construction (TG_TABLE_NAME, to_jsonb) : brancher une nouvelle '
  'table fille sur ce trigger suffit, aucune branche par nom de table à maintenir.';

create trigger trg_parent_lock
  before insert or update on public.occurrence_comments
  for each row execute function public.enforce_parent_occurrence_lock();

create trigger trg_parent_lock
  before insert or update on public.occurrence_checklist_items
  for each row execute function public.enforce_parent_occurrence_lock();

create trigger trg_parent_lock
  before insert or update on public.documents
  for each row execute function public.enforce_parent_occurrence_lock();

