create view public.validation_queue
  with (security_invoker = true)
  as
  select oc.id,
         oc.obligation_type_id,
         oc.period_key,
         oc.period_start,
         oc.legal_due_date,
         oc.internal_due_date,
         oc.status,
         oc.version,
         oc.owner_id,
         oc.validator_id,
         oc.submitted_for_validation_at,
         ot.code as obligation_code,
         ot.name as obligation_name,
         ot.criticality,
         ot.validation_levels,
         dom.code as domain_code,
         au.name as authority_name,
         owner.full_name as owner_name,
         public.validation_steps_obtained(oc.id) as validations_obtained,
         (oc.internal_due_date - (pg_catalog.now() at time zone 'Africa/Algiers')::date)
           as days_to_internal
  from public.obligation_occurrences oc
  join public.obligation_types ot on ot.id = oc.obligation_type_id
  left join public.domains dom on dom.id = ot.domain_id
  left join public.authorities au on au.id = ot.authority_id
  left join public.profiles owner on owner.id = oc.owner_id
  where oc.status = 'PENDING_VALIDATION'
    and oc.deleted_at is null
    and public.can_validate_occurrence(oc.id)
    and not public.self_validation_blocked(
          oc.obligation_type_id, oc.owner_id, public.current_profile_id());

comment on view public.validation_queue is
  'Dossiers en attente de la validation de l''appelant, délégations comprises — '
  'c''est `can_validate_occurrence` qui les intègre, et non un filtre recopié ici. '
  'security_invoker : la politique des occurrences s''applique, donc le '
  'cloisonnement par domaine. La séparation des pouvoirs est appliquée dans la vue '
  'ET par le trigger : proposer un dossier qu''on ne pourra pas valider est une '
  'promesse que la base démentira au clic.';

grant select on public.validation_queue to authenticated;

-- -----------------------------------------------------------------------------
-- Le compteur de navigation s'aligne sur la file
-- -----------------------------------------------------------------------------

/*
 * ⚠️ DIVERGENCE CORRIGÉE. Depuis 0005, le compteur « à valider » de la barre
 * latérale comptait les dossiers en attente que l'appelant peut valider — mais
 * SANS écarter ceux dont il est lui-même le préparateur. La file, elle, les
 * écarte, puisque la séparation des pouvoirs les lui interdit. Un responsable
 * qui prépare ses propres dossiers voyait donc une pastille annonçant trois
 * dossiers pour une file qui n'en montrait qu'un.
 *
 * Le compteur ne recopie plus la condition : il appelle la MÊME fonction que la
 * file. Deux définitions d'un même nombre finissent toujours par diverger.
 */
create or replace function public.navigation_counters()
returns table (
  overdue int,
  pending_validation int,
  my_tasks int
)
language sql
stable
security invoker
set search_path = ''
as $fn$
  select
    -- Même définition que occurrence_list.is_overdue : la pastille de la barre
    -- latérale et la colonne de la liste doivent donner le même nombre.
    count(*) filter (
      where oc.legal_due_date < (now() at time zone 'Africa/Algiers')::date
        and not (oc.status = any (public.overdue_exempt_statuses()))
    )::int,
    public.pending_validation_count(),
    count(*) filter (
      where oc.owner_id = public.current_profile_id()
        and oc.status in ('TODO', 'IN_PROGRESS', 'REJECTED')
    )::int
  from public.obligation_occurrences oc
  where oc.deleted_at is null
$fn$;

comment on function public.navigation_counters() is
  '⚠️ SECURITY INVOKER. Les trois compteurs ne portent que sur les lignes que la RLS
   laisse voir. Le compteur de retard emploie overdue_exempt_statuses(), et celui
   des validations appelle pending_validation_count() — la MÊME fonction que la
   file /validation. Un écart entre une pastille et l''écran qu''elle annonce se
   lit comme un défaut, et détruit la confiance dans les deux.';

-- =============================================================================
-- 10. DÉLÉGATIONS — révocation
-- =============================================================================

create or replace function public.revoke_validation_delegation(
  p_delegation_id uuid,
  p_reason text
)
returns boolean
language plpgsql
security definer
set search_path = ''
as $fn$
declare
  target public.validation_delegations%rowtype;
  affected int;
begin
  select * into target from public.validation_delegations where id = p_delegation_id;
  if target.id is null then
    raise exception 'Délégation introuvable.' using errcode = '42501';
  end if;

  -- Le délégant reprend ses droits quand il veut ; la DIRECTION arbitre.
  if not (target.delegator_id = public.current_profile_id() or public.is_direction(auth.uid())) then
    raise exception 'Révocation réservée au délégant ou à la Direction.' using errcode = '42501';
  end if;

  if p_reason is null or length(trim(p_reason)) < 10 then
    raise exception 'Un motif d''au moins 10 caractères est requis.' using errcode = '22023';
  end if;

  update public.validation_delegations
  set revoked_at = pg_catalog.now(),
      revoked_by = public.current_profile_id(),
      reason = target.reason || ' — révoquée : ' || trim(p_reason)
  where id = p_delegation_id and revoked_at is null;

  get diagnostics affected = row_count;
  return affected = 1;
end;
$fn$;

comment on function public.revoke_validation_delegation(uuid, text) is
  'Révocation immédiate. Motif obligatoire, concaténé au motif d''origine : le '
  'journal doit dire pourquoi la délégation a été ouverte ET pourquoi elle a été '
  'refermée. La ligne est CONSERVÉE — une délégation supprimée effacerait la '
  'justification des actions faites sous son couvert.';

grant execute on function public.revoke_validation_delegation(uuid, text) to authenticated;
