-- -----------------------------------------------------------------------------
-- Application des effets — dans la transaction de la transition
-- -----------------------------------------------------------------------------

create or replace function public.dispatch_transition_notifications(
  p_occurrence public.obligation_occurrences,
  p_from public.occurrence_status,
  p_to public.occurrence_status,
  p_reason text
)
returns void
language plpgsql
security definer
set search_path = ''
as $fn$
declare
  effect record;
  recipient uuid;
begin
  for effect in
    select * from public.transition_notifications
    where from_status is not distinct from p_from and to_status = p_to
  loop
    if effect.recipient = 'VALIDATOR' then
      -- Le validateur désigné ; à défaut, le responsable du dossier — mieux vaut
      -- prévenir quelqu'un que personne.
      recipient := coalesce(p_occurrence.validator_id, p_occurrence.owner_id);
      if recipient is not null then
        insert into public.notifications (recipient_id, kind, occurrence_id, actor_id, reason)
        values (recipient, effect.kind, p_occurrence.id, public.app_actor_id(),
                case when effect.include_reason then p_reason else null end);
      end if;

    elsif effect.recipient = 'OWNER' then
      if p_occurrence.owner_id is not null then
        insert into public.notifications (recipient_id, kind, occurrence_id, actor_id, reason)
        values (p_occurrence.owner_id, effect.kind, p_occurrence.id, public.app_actor_id(),
                case when effect.include_reason then p_reason else null end);
      end if;

    elsif effect.recipient = 'DIRECTION' then
      -- Tous les comptes DIRECTION actifs. Le destinataire n'est pas une personne
      -- nommée mais une fonction : nommer quelqu'un ici le rendrait indispensable.
      insert into public.notifications (recipient_id, kind, occurrence_id, actor_id, reason)
      select distinct ur.user_id, effect.kind, p_occurrence.id, public.app_actor_id(),
             case when effect.include_reason then p_reason else null end
      from public.user_roles ur
      join public.roles r on r.id = ur.role_id
      where r.code = 'DIRECTION'
        and ur.revoked_at is null
        and (ur.expires_at is null or ur.expires_at > pg_catalog.now())
        -- Ne pas s'écrire à soi-même : l'auteur de l'action sait ce qu'il vient de faire.
        and ur.user_id is distinct from public.app_actor_id();
    end if;
  end loop;
end;
$fn$;

comment on function public.dispatch_transition_notifications is
  'Applique les effets déclarés dans transition_notifications. Appelée par le '
  'trigger qui journalise la transition : mêmes transaction, même verrou, même '
  'destin. Aucune branche par statut — la table dit qui prévenir.';

-- =============================================================================
-- 4. DOUBLE NIVEAU DE VALIDATION
-- =============================================================================

/*
 * Principe : la première validation n'est pas un changement d'état, c'est une
 * ÉTAPE. Elle est inscrite dans `occurrence_transitions` avec from = to =
 * PENDING_VALIDATION et `metadata->>'origin' = 'VALIDATION_STEP'`. Le compteur
 * de validations obtenues est donc porté par le journal lui-même, et non par une
 * colonne qu'il faudrait tenir à jour — le journal ne peut pas mentir, il est
 * append-only.
 *
 * L'épisode courant commence à la dernière entrée en PENDING_VALIDATION : un
 * dossier rejeté puis resoumis repart de zéro, ce qui est la seule lecture
 * défendable — la première validation portait sur un dossier différent.
 */

create or replace function public.validation_steps_obtained(p_occurrence_id uuid)
returns int
language sql
stable
security definer
set search_path = ''
as $fn$
  -- ⚠️ L'épisode est délimité par l'IDENTIFIANT de la ligne, jamais par sa date.
  -- `created_at` vaut `now()`, c'est-à-dire l'heure de DÉBUT DE TRANSACTION : une
  -- validation, un rejet et une resoumission enchaînés dans la même transaction
  -- portent tous le même horodatage, et un `>=` sur la date compterait alors une
  -- validation périmée comme acquise. La séquence, elle, est strictement croissante.
  select count(*)::int
  from public.occurrence_transitions t
  where t.occurrence_id = p_occurrence_id
    and t.metadata ->> 'origin' = 'VALIDATION_STEP'
    and t.id > coalesce((
      select max(entry.id)
      from public.occurrence_transitions entry
      where entry.occurrence_id = p_occurrence_id
        and entry.to_status = 'PENDING_VALIDATION'
        and entry.from_status is distinct from 'PENDING_VALIDATION'
    ), 0);
$fn$;

comment on function public.validation_steps_obtained(uuid) is
  'Nombre de validations de premier niveau déjà obtenues pour l''épisode d''attente '
  'EN COURS. Compté dans le journal append-only plutôt que stocké dans une colonne : '
  'un compteur qu''on met à jour est un compteur qu''on peut désynchroniser. '
  'Un rejet suivi d''une nouvelle soumission remet le compte à zéro — la première '
  'validation portait sur un dossier qui n''existe plus.';

create or replace function public.validation_levels_required(p_occurrence_id uuid)
returns int
language sql
stable
security definer
set search_path = ''
as $fn$
  select coalesce(ot.validation_levels, 1)
  from public.obligation_occurrences oc
  join public.obligation_types ot on ot.id = oc.obligation_type_id
  where oc.id = p_occurrence_id;
$fn$;

create or replace function public.is_direction(p_user_id uuid)
returns boolean
language sql
stable
security definer
set search_path = ''
as $fn$
  select exists (
    select 1
    from public.user_roles ur
    join public.roles r on r.id = ur.role_id
    where ur.user_id = p_user_id
      and r.code = 'DIRECTION'
      and ur.revoked_at is null
      and (ur.expires_at is null or ur.expires_at > pg_catalog.now())
  );
$fn$;

comment on function public.is_direction(uuid) is
  'Appartenance à la DIRECTION, rôle actif. Extraite parce que trois fonctions la '
  'posaient chacune de leur côté ; une règle d''appartenance dupliquée finit par '
  'diverger, et c''est toujours la variante la plus permissive qui l''emporte.';

create or replace function public.record_validation_step(p_occurrence_id uuid)
returns int
language plpgsql
security definer
set search_path = ''
as $fn$
declare
  obtained int;
begin
  insert into public.occurrence_transitions
    (occurrence_id, from_status, to_status, actor_id, on_behalf_of_id, reason, metadata)
  values (
    p_occurrence_id,
    'PENDING_VALIDATION',
    'PENDING_VALIDATION',
    public.app_actor_id(),
    (
      select d.delegator_id
      from public.validation_delegations d
      where d.delegate_id = auth.uid()
        and d.revoked_at is null
        and current_date between d.starts_at and d.ends_at
      limit 1
    ),
    null,
    jsonb_build_object('origin', 'VALIDATION_STEP', 'level', 1)
  );

  obtained := public.validation_steps_obtained(p_occurrence_id);
  return obtained;
end;
$fn$;

comment on function public.record_validation_step(uuid) is
  'Inscrit une validation de premier niveau SANS changer l''état. Le dossier reste '
  'en attente, et l''historique porte la trace nominative de qui a validé quoi.';

-- =============================================================================
-- 5. LA FONCTION QUI DÉCIDE
-- =============================================================================

create or replace function public.evaluate_transition(
  p_occurrence_id uuid,
  p_to_status public.occurrence_status,
  p_reason text default null,
  p_reference_number text default null,
  p_late_reason_code public.late_reason_code default null
)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $fn$
declare
  occ public.obligation_occurrences%rowtype;
  rule public.status_transition_rules%rowtype;
  occ_domain uuid;
  needs_proof boolean;
  missing text[];
  today_algiers date := (pg_catalog.now() at time zone 'Africa/Algiers')::date;
  reason_clean text := nullif(pg_catalog.btrim(coalesce(p_reason, '')), '');
  levels int;
  obtained int;
begin
  if not public.can_see_occurrence(p_occurrence_id) then
    -- Indistinguable d'un identifiant inexistant : l'écart de message permettrait
    -- d'énumérer les dossiers des autres domaines.
    return jsonb_build_object('outcome', 'NOT_FOUND');
  end if;

  select * into occ from public.obligation_occurrences where id = p_occurrence_id;
  if occ.id is null then
    return jsonb_build_object('outcome', 'NOT_FOUND');
  end if;

  if occ.status = p_to_status then
    return jsonb_build_object('outcome', 'NO_CHANGE', 'version', occ.version);
  end if;

  -- ── La transition existe-t-elle ? ─────────────────────────────────────────
  -- Lue dans status_transition_rules, jamais écrite en dur.
  select * into rule
  from public.status_transition_rules
  where from_status = occ.status and to_status = p_to_status;

  if rule.id is null then
    return jsonb_build_object(
      'outcome', 'INVALID_TRANSITION', 'from', occ.status, 'to', p_to_status);
  end if;

  -- ── Verrou ────────────────────────────────────────────────────────────────
  -- Une seule porte de sortie, celle de `enforce_occurrence_lock` : la
  -- réouverture d'un dossier archivé.
  if occ.is_locked and not (occ.status = 'ARCHIVED' and p_to_status = 'SUBMITTED') then
    return jsonb_build_object('outcome', 'LOCKED');
  end if;

  -- ── Habilitation ──────────────────────────────────────────────────────────
  occ_domain := public.obligation_domain_of_type(occ.obligation_type_id);

  if rule.required_permission = 'occurrence.validate' then
    -- can_validate_occurrence intègre le filet DIRECTION passé le délai d'attente.
    if not public.can_validate_occurrence(p_occurrence_id) then
      return jsonb_build_object('outcome', 'FORBIDDEN', 'permission', rule.required_permission);
    end if;
  elsif not public.has_permission_in_domain(rule.required_permission, occ_domain) then
    return jsonb_build_object('outcome', 'FORBIDDEN', 'permission', rule.required_permission);
  end if;

  -- ── Motif ─────────────────────────────────────────────────────────────────
  if rule.requires_reason and reason_clean is null then
    return jsonb_build_object('outcome', 'REASON_REQUIRED');
  end if;

  -- ── Complétude du dossier ─────────────────────────────────────────────────
  if p_to_status = 'PENDING_VALIDATION' then
    missing := public.occurrence_missing_items(p_occurrence_id);
    if pg_catalog.array_length(missing, 1) is not null then
      return jsonb_build_object('outcome', 'INCOMPLETE', 'missing', to_jsonb(missing));
    end if;
  end if;

  -- ── Séparation des pouvoirs, et niveaux de validation ─────────────────────
  if p_to_status = 'VALIDATED' then
    if public.self_validation_blocked(
         occ.obligation_type_id, occ.owner_id, public.current_profile_id()) then
      return jsonb_build_object('outcome', 'SELF_VALIDATION_BLOCKED');
    end if;

    levels := public.validation_levels_required(p_occurrence_id);
    obtained := public.validation_steps_obtained(p_occurrence_id);

    if levels > 1 then
      if obtained = 0 then
        -- Première validation : elle compte, mais ne change pas l'état.
        return jsonb_build_object(
          'outcome', 'ALLOWED', 'effect', 'PARTIAL_VALIDATION',
          'obtained', obtained, 'required', levels, 'version', occ.version);
      end if;

      -- Second niveau : réservé à la DIRECTION, par décision arrêtée.
      if not public.is_direction(auth.uid()) then
        return jsonb_build_object(
          'outcome', 'SECOND_LEVEL_REQUIRES_DIRECTION',
          'obtained', obtained, 'required', levels);
      end if;
    end if;
  end if;

  -- ── Dépôt : preuve, référence, motif de retard ────────────────────────────
  if p_to_status = 'SUBMITTED' and occ.status = 'VALIDATED' then
    select ot.requires_proof into needs_proof
    from public.obligation_types ot where ot.id = occ.obligation_type_id;

    if coalesce(needs_proof, false) then
      if nullif(pg_catalog.btrim(coalesce(p_reference_number, occ.reference_number, '')), '') is null then
        return jsonb_build_object('outcome', 'REFERENCE_REQUIRED');
      end if;
      if not exists (
        select 1 from public.documents d
        where d.occurrence_id = p_occurrence_id
          and d.document_kind = 'PREUVE_DEPOT'
          and d.deleted_at is null
      ) then
        return jsonb_build_object('outcome', 'PROOF_REQUIRED');
      end if;
    end if;

    -- ⚠️ Motif de retard OBLIGATOIRE au-delà de l'échéance légale. C'est le seul
    -- moment où l'information est encore fraîche ; réclamée plus tard, elle est
    -- reconstruite, donc fausse.
    if occ.legal_due_date < today_algiers
       and coalesce(p_late_reason_code, occ.late_reason_code) is null then
      return jsonb_build_object('outcome', 'LATE_REASON_REQUIRED', 'dueDate', occ.legal_due_date);
    end if;
  end if;

  return jsonb_build_object(
    'outcome', 'ALLOWED', 'effect', 'FULL', 'version', occ.version, 'label', rule.label);
end;
$fn$;

comment on function public.evaluate_transition is
  '⚠️ SOURCE UNIQUE de la décision « cette transition est-elle possible, et sinon '
  'pourquoi ». Consultée par `apply_occurrence_transition` avant d''écrire, et par '
  'le service TypeScript `canTransition` pour griser un bouton et en expliquer la '
