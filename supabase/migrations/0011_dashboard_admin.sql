create or replace function public.log_audit_export(p_filters jsonb, p_row_count int)
returns void
language plpgsql
security definer
set search_path = ''
as $fn$
begin
  if not public.has_permission('audit.read') then
    raise exception 'Export refusé : audit.read requis.' using errcode = '42501';
  end if;

  insert into public.audit_log (
    actor_id, actor_email, action, entity_table, entity_id_ref, after
  )
  values (
    auth.uid(),
    (select p.email::text from public.profiles p where p.id = auth.uid()),
    'EXPORT', 'audit_log', null,
    jsonb_build_object('filters', p_filters, 'row_count', p_row_count)
  );
end;
$fn$;

comment on function public.log_audit_export(jsonb, int) is
  '⚠️ L''export du journal est lui-même journalisé, avec ses filtres et son '
  'volume. Sans cela, le seul geste capable de faire sortir l''intégralité de la '
  'traçabilité de l''entreprise serait le seul à ne pas en laisser.';

grant execute on function public.log_audit_export(jsonb, int) to authenticated;

