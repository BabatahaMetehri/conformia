/*
 * ⚠️ REVIREMENT ASSUMÉ. 0002 disait : « Aucune politique d'écriture — la matrice
 * des rôles système ne se modifie pas à chaud. » L'écran d'administration des
 * rôles demandé ici exige l'inverse.
 *
 * Le compromis retenu : la matrice devient modifiable, mais
 *   • seul `role.manage` écrit ;
 *   • un rôle SYSTÈME ne peut être ni supprimé ni renommé (trigger ci-dessous) ;
 *   • chaque modification est auditée ligne par ligne.
 *
 * Ce qui n'est PAS protégé, et doit être dit : rien n'empêche de retirer à
 * DIRECTION la permission `occurrence.validate`. Une matrice modifiable est une
 * matrice qu'on peut casser ; l'écran affiche un avertissement chiffré avant
 * toute réduction touchant des comptes actifs, et l'audit permet de revenir en
 * arrière. Verrouiller davantage reviendrait à ne pas livrer l'écran.
 */
-- Le trigger d'audit existe déjà sur cette table depuis 0003 : la matrice était
-- déjà surveillée, elle était simplement en lecture seule.
grant insert, delete on public.role_permissions to authenticated;

create policy role_permissions_insert on public.role_permissions
  for insert to authenticated
  with check (public.is_active_user() and public.has_permission('role.manage'));

create policy role_permissions_delete on public.role_permissions
  for delete to authenticated
  using (public.is_active_user() and public.has_permission('role.manage'));

comment on policy role_permissions_insert on public.role_permissions is
  'Édition de la matrice, réservée à role.manage. Chaque case cochée ou décochée '
  'produit une entrée d''audit : une extension de droits doit être reconstituable.';

create or replace function public.protect_system_roles()
returns trigger
language plpgsql
set search_path = ''
as $fn$
begin
  if tg_op = 'DELETE' then
    if old.is_system then
      raise exception 'Le rôle système % ne peut pas être supprimé.', old.code
        using errcode = '42501';
    end if;
    return old;
  end if;

  if old.is_system and (new.code is distinct from old.code
                        or new.is_system is distinct from old.is_system) then
    raise exception 'Le code d''un rôle système est immuable.'
      using errcode = '42501';
  end if;

  return new;
end;
$fn$;

comment on function public.protect_system_roles() is
  'Un rôle système est un point d''ancrage : `roles.code` est comparé en dur dans '
  'les fonctions d''autorisation (DIRECTION notamment). Le renommer ou le '
  'supprimer romprait ces comparaisons en silence. Ses PERMISSIONS, elles, '
  'restent modifiables — c''est le sens de l''écran.';

create trigger trg_roles_protect_system
  before update or delete on public.roles
  for each row execute function public.protect_system_roles();

/** Comptes actifs qu'une réduction de droits toucherait — pour avertir avant. */
create or replace function public.role_holder_count(p_role_id uuid)
returns int
language sql
stable
security definer
set search_path = ''
as $fn$
  select count(distinct ur.user_id)::int
  from public.user_roles ur
  join public.profiles p on p.id = ur.user_id
  where ur.role_id = p_role_id
    and ur.revoked_at is null
    and (ur.expires_at is null or ur.expires_at > now())
    and p.deactivated_at is null;
$fn$;

grant execute on function public.role_holder_count(uuid) to authenticated;

