create or replace function public.reset_user_mfa(p_user_id uuid, p_reason text)
returns boolean
language plpgsql
security definer
set search_path = ''
as $fn$
declare
  target record;
  affected int;
begin
  if not public.has_permission('user.manage') then
    raise exception 'Réinitialisation MFA refusée : user.manage requis.' using errcode = '42501';
  end if;
  if p_reason is null or length(trim(p_reason)) < 10 then
    raise exception 'Un motif d''au moins 10 caractères est requis.' using errcode = '22023';
  end if;

  select id, email, full_name into target from public.profiles where id = p_user_id;
  if target.id is null then
    raise exception 'Compte introuvable.' using errcode = '42501';
  end if;

  update public.profiles set mfa_enrolled = false where id = p_user_id;
  get diagnostics affected = row_count;

  -- ⚠️ Retirer le second facteur de quelqu'un est le geste qui permet de prendre
  -- sa place. Il est donc journalisé nommément, et la DIRECTION en est informée
  -- SANS pouvoir l'empêcher : le contre-pouvoir est la visibilité, pas le veto.
  insert into public.audit_log (
    actor_id, actor_email, action, entity_table, entity_id_ref, after
  )
  values (
    auth.uid(),
    (select p.email::text from public.profiles p where p.id = auth.uid()),
    'MFA_RESET', 'profiles', p_user_id::text,
    jsonb_build_object('reason', trim(p_reason), 'target_email', target.email::text)
  );

  insert into public.notifications (recipient_id, kind, actor_id, reason)
  select distinct ur.user_id, 'MFA_RESET', public.app_actor_id(),
         'Second facteur réinitialisé pour ' || coalesce(target.full_name, target.email::text)
         || ' — ' || trim(p_reason)
  from public.user_roles ur
  join public.roles r on r.id = ur.role_id
  where r.code = 'DIRECTION'
    and ur.revoked_at is null
    and (ur.expires_at is null or ur.expires_at > now());

  return affected = 1;
end;
$fn$;

comment on function public.reset_user_mfa(uuid, text) is
  'Retire l''enrôlement du second facteur. Motif obligatoire, entrée d''audit '
  'nominative, DIRECTION notifiée. Aucune de ces trois traces n''est facultative.';

grant execute on function public.reset_user_mfa(uuid, text) to authenticated;

