-- ── Conformité mensuelle, 12 mois glissants ─────────────────────────────────
create materialized view public.dashboard_compliance_monthly as
select
  ot.domain_id,
  date_trunc('month', oc.legal_due_date)::date as month,
  count(*)::int as due_count,
  count(*) filter (
    where oc.submitted_at is not null
      and (oc.submitted_at at time zone 'Africa/Algiers')::date <= oc.legal_due_date
  )::int as on_time_count
from public.obligation_occurrences oc
join public.obligation_types ot on ot.id = oc.obligation_type_id
where oc.deleted_at is null
  and oc.status <> 'NOT_APPLICABLE'
  and oc.legal_due_date >= (date_trunc('month', now() at time zone 'Africa/Algiers') - interval '11 months')::date
  and oc.legal_due_date < (date_trunc('month', now() at time zone 'Africa/Algiers') + interval '1 month')::date
group by ot.domain_id, date_trunc('month', oc.legal_due_date);

