-- 0011 — TABLEAU DE BORD ET ADMINISTRATION
--
-- Deux modules, une seule migration, parce qu'ils partagent trois mécanismes :
-- les vues matérialisées, les notifications, et le journal d'audit.
--
-- ⚠️ RAPPEL CENTRAL SUR LES VUES MATÉRIALISÉES. PostgreSQL n'applique PAS la RLS
-- à une matview. Toutes celles créées ici sont donc agrégées PAR DOMAINE, ne
-- reçoivent AUCUN grant, et ne sont lisibles que par une fonction
-- `*_for_caller()` qui réapplique le cloisonnement ligne par ligne. C'est la
-- convention posée en 0007 et elle est reconduite à l'identique : un agrégat
-- fuit aussi sûrement qu'une liste, et un COUNT par domaine renseigne sur la
-- charge de travail d'un service qu'on n'a pas le droit de voir.
-- =============================================================================

