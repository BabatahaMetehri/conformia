create or replace function public.refresh_dashboard_views()
returns void
language plpgsql
security definer
set search_path = ''
as $fn$
declare
  view_name text;
begin
  foreach view_name in array array[
    'dashboard_compliance_monthly', 'dashboard_upcoming_load',
    'dashboard_late_reasons', 'dashboard_workload', 'dashboard_health']
  loop
    begin
      -- CONCURRENTLY : le tableau de bord continue d'être lu pendant le calcul.
      execute format('refresh materialized view concurrently public.%I', view_name);
    exception
      when others then
        -- Premier rafraîchissement : la forme concurrente exige une vue déjà
        -- peuplée. On retombe sur la forme bloquante plutôt que de laisser les
        -- agrégats figés indéfiniment.
        execute format('refresh materialized view public.%I', view_name);
    end;
  end loop;
end;
$fn$;

