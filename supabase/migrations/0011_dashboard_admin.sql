/**
 * Applique des échéances recalculées, toutes obligations confondues.
 *
 * ⚠️ Diffère de `recalculate_todo_due_dates` (0006), qui ne porte que sur UNE
 * obligation : un jour férié ajouté déplace potentiellement les échéances de
 * toutes. Les quatre bornes sont les mêmes, et pour la même raison — on ne
 * déplace pas le sol sous les pieds de quelqu'un qui a déjà commencé.
 */
create or replace function public.apply_due_date_updates(p_updates jsonb, p_reason text)
returns int
language plpgsql
security definer
set search_path = ''
as $fn$
declare
  updated_count int;
begin
  if not public.has_permission('referential.manage') then
    raise exception 'Recalcul refusé : referential.manage requis.' using errcode = '42501';
  end if;
  if p_updates is null or jsonb_typeof(p_updates) <> 'array' then
    raise exception 'Recalcul refusé : liste de mises à jour attendue.' using errcode = '22023';
  end if;

  with proposed as (
    select (item ->> 'occurrence_id')::uuid as occurrence_id,
           (item ->> 'legal_due_date')::date as legal_due_date,
           (item ->> 'internal_due_date')::date as internal_due_date
    from jsonb_array_elements(p_updates) as item
  ),
  applied as (
    update public.obligation_occurrences oc
       set legal_due_date = p.legal_due_date,
           internal_due_date = p.internal_due_date,
           updated_at = now()
      from proposed p
     where oc.id = p.occurrence_id
       and oc.status = 'TODO'
       and oc.is_locked = false
       and oc.deleted_at is null
       and (oc.legal_due_date is distinct from p.legal_due_date
            or oc.internal_due_date is distinct from p.internal_due_date)
    returning oc.id, oc.owner_id
  ),
  notified as (
    -- Le responsable doit apprendre que SON échéance a bougé. Un calendrier qui
    -- se déplace en silence est pire qu'un calendrier faux : on continue de se
    -- fier à la date qu'on avait notée.
    insert into public.notifications (recipient_id, kind, occurrence_id, actor_id, reason)
    select a.owner_id, 'HOLIDAY_CALENDAR_CHANGED', a.id, public.app_actor_id(), p_reason
    from applied a
    where a.owner_id is not null
    returning 1
  )
  select count(*) into updated_count from applied;

  return updated_count;
end;
$fn$;

comment on function public.apply_due_date_updates(jsonb, text) is
  'Propage des échéances recalculées aux SEULES occurrences TODO non verrouillées, '
  'et prévient leurs responsables. Le calcul lui-même est fait par le service de '
  'planification, qui connaît les règles d''échéance et le calendrier — la base '
  'applique, elle ne recalcule pas.';

grant execute on function public.apply_due_date_updates(jsonb, text) to authenticated;

