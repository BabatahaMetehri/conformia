/*
 * Une invitation portant un rôle temporaire DOIT porter une expiration.
 *
 * ⚠️ Le contrôle est répété ici alors que `enforce_role_max_duration` le fera à
 * l'attribution. Ce n'est pas une duplication de règle mais une anticipation :
 * sans lui, l'invitation partirait, la personne créerait son compte, et
 * l'attribution du rôle échouerait — laissant un compte sans droits et personne
 * pour comprendre pourquoi. La borne, elle, reste une donnée de
 * `roles.max_duration_days`, lue et non recopiée.
 */
create or replace function public.enforce_invitation_role_duration()
returns trigger
language plpgsql
security definer
set search_path = ''
as $fn$
declare
  max_days int;
  role_code text;
begin
  select r.max_duration_days, r.code into max_days, role_code
  from public.roles r where r.id = new.role_id;

  if max_days is null then
    return new;
  end if;

  if new.role_expires_at is null then
    raise exception 'Le rôle % exige une date d''expiration (maximum % jours).',
      role_code, max_days using errcode = '23514';
  end if;
  if new.role_expires_at > new.created_at + make_interval(days => max_days) then
    raise exception 'Le rôle % est limité à % jours.', role_code, max_days
      using errcode = '23514';
  end if;

  return new;
end;
$fn$;

create trigger trg_invitation_role_duration
  before insert or update on public.user_invitations
  for each row execute function public.enforce_invitation_role_duration();

