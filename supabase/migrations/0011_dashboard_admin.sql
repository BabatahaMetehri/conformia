-- 3. DÉSACTIVATION D'UN COMPTE — refusée tant qu'il porte du travail
-- =============================================================================

create or replace function public.open_task_count(p_user_id uuid)
returns int
language sql
stable
security definer
set search_path = ''
as $fn$
  -- ⚠️ `overdue_exempt_statuses()` porte un nom de compteur de retard, mais
  -- énumère exactement les états TERMINÉS : déposé, archivé, sans objet. « Encore
  -- ouvert » et « n'arrête pas le compteur de retard » ont ici la même réponse, et
  -- 0007 a justement supprimé la seconde liste parce que deux définitions
  -- donnaient deux chiffres pour la même question. On réemploie donc celle-ci.
  select count(*)::int
  from public.obligation_occurrences oc
  where oc.deleted_at is null
    and not (oc.status = any (public.overdue_exempt_statuses()))
    and (oc.owner_id = p_user_id or oc.validator_id = p_user_id);
$fn$;

comment on function public.open_task_count(uuid) is
  'Dossiers encore ouverts dont la personne est responsable OU validateur. '
  'Les deux rôles comptent : désactiver le seul validateur d''un dossier le bloque '
  'aussi sûrement que d''en désactiver le préparateur.';

grant execute on function public.open_task_count(uuid) to authenticated;

create or replace function public.enforce_deactivation_requires_handover()
returns trigger
language plpgsql
security definer
set search_path = ''
as $fn$
declare
  remaining int;
begin
  if new.deactivated_at is null or old.deactivated_at is not null then
    return new;
  end if;

  remaining := public.open_task_count(new.id);

  if remaining > 0 then
    raise exception
      'Désactivation refusée : % dossier(s) ouvert(s) restent affectés à ce compte.', remaining
      using errcode = '23514',
            hint = 'Réaffecter les dossiers à une autre personne avant de désactiver.';
  end if;

  return new;
end;
$fn$;

comment on function public.enforce_deactivation_requires_handover() is
  '⚠️ Un compte désactivé qui porte encore des dossiers les rend ORPHELINS : ils '
  'restent dus, plus personne ne les voit dans « mes tâches », et l''échéance '
  'passe sans que quiconque ait été prévenu. La réaffectation est donc un '
  'PRÉALABLE, imposé en base — l''écran qui demande un destinataire est un '
  'confort, ce trigger est la garantie.';

create trigger trg_profiles_deactivation_handover
  before update on public.profiles
  for each row execute function public.enforce_deactivation_requires_handover();

/**
 * Désactive un compte, en réaffectant d'abord ce qu'il porte.
 *
 * ⚠️ EXISTE PARCE QUE `profiles_update` (0002) ne laisse modifier QUE son propre
 * profil — et c'est une bonne politique : personne ne doit pouvoir réécrire la
 * fiche d'un collègue. Un administrateur n'a donc aucun moyen de désactiver
 * quelqu'un par un UPDATE, et il ne doit pas en avoir : il a besoin de CE
 * geste-ci, borné, et d'aucun autre.
 *
 * La réaffectation et la désactivation sont dans la MÊME transaction. Séparées,
 * elles laisseraient une fenêtre où le compte est fermé et les dossiers encore
 * à lui — exactement l'état d'orphelinat que le trigger existe pour empêcher.
 */
create or replace function public.deactivate_user(
  p_user_id uuid,
  p_reason text,
  p_handover_to uuid default null
)
returns int
language plpgsql
security definer
set search_path = ''
as $fn$
declare
  moved int := 0;
begin
  if not public.has_permission('user.manage') then
    raise exception 'Désactivation refusée : user.manage requis.' using errcode = '42501';
  end if;
  if p_reason is null or length(trim(p_reason)) < 10 then
    raise exception 'Un motif d''au moins 10 caractères est requis.' using errcode = '22023';
  end if;

  -- Se désactiver soi-même verrouillerait l'installation si l'on est le dernier
  -- administrateur, et il n'existe aucun chemin de retour.
  if p_user_id = public.current_profile_id() then
    raise exception 'Un administrateur ne peut pas désactiver son propre compte.'
      using errcode = '42501';
  end if;

  if p_handover_to is not null then
    if p_handover_to = p_user_id then
      raise exception 'Le destinataire doit être une autre personne.' using errcode = '22023';
    end if;

    update public.obligation_occurrences
    set owner_id = case when owner_id = p_user_id then p_handover_to else owner_id end,
        validator_id = case when validator_id = p_user_id then p_handover_to else validator_id end,
        updated_at = now()
    where deleted_at is null
      and not (status = any (public.overdue_exempt_statuses()))
      and (owner_id = p_user_id or validator_id = p_user_id);

    get diagnostics moved = row_count;
  end if;

  -- Le trigger `enforce_deactivation_requires_handover` refuse s'il reste
  -- quoi que ce soit : c'est lui la garantie, pas la réaffectation ci-dessus.
  update public.profiles
  set deactivated_at = now(), deactivated_by = public.current_profile_id(), is_active = false
  where id = p_user_id;

  insert into public.audit_log (
    actor_id, actor_email, action, entity_table, entity_id_ref, after
  )
  values (
    auth.uid(),
    (select pr.email::text from public.profiles pr where pr.id = auth.uid()),
    'UPDATE', 'profiles', p_user_id::text,
    jsonb_build_object('deactivated', true, 'reason', trim(p_reason),
                       'handover_to', p_handover_to, 'reassigned', moved)
  );

  return moved;
end;
$fn$;

comment on function public.deactivate_user(uuid, text, uuid) is
  'Réaffecte puis désactive, en une transaction. Motif obligatoire. Refuse '
  'l''auto-désactivation. Le destinataire est facultatif POUR LA FONCTION — un '
  'compte sans dossier n''en a pas besoin — mais le trigger refusera la '
  'désactivation s''il en reste, ce qui rend le destinataire obligatoire dans les '
  'seuls cas où il l''est réellement.';

grant execute on function public.deactivate_user(uuid, text, uuid) to authenticated;

