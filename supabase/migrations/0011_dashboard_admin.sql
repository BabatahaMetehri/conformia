-- ── Complétude documentaire, et ancienneté des validations ──────────────────
create materialized view public.dashboard_health as
select
  ot.domain_id,
  count(*) filter (where oc.status = 'PENDING_VALIDATION')::int as pending_validation,
  coalesce(avg(
    extract(epoch from (now() - oc.submitted_for_validation_at)) / 86400
  ) filter (where oc.status = 'PENDING_VALIDATION'), 0)::numeric(10, 2) as pending_avg_days,
  coalesce(sum(ci.required_total), 0)::int as documents_required,
  coalesce(sum(ci.provided_total), 0)::int as documents_provided
from public.obligation_occurrences oc
join public.obligation_types ot on ot.id = oc.obligation_type_id
left join lateral (
  select count(*) filter (where c.is_mandatory)::int as required_total,
         count(*) filter (where c.is_mandatory and c.is_checked)::int as provided_total
  from public.occurrence_checklist_items c
  where c.occurrence_id = oc.id
) ci on true
where oc.deleted_at is null
  and not (oc.status = any (public.overdue_exempt_statuses()))
group by ot.domain_id;

